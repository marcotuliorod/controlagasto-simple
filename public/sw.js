// Custom Service Worker for Push Notifications with Workbox
import { precacheAndRoute } from 'workbox-precaching';
import { registerRoute, NavigationRoute } from 'workbox-routing';
import { NetworkFirst, CacheFirst } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import { clientsClaim } from 'workbox-core';

console.log('[Service Worker] 🚀 SW file loaded - version 1.0.0');

// Ativar novo SW imediatamente
self.skipWaiting();
clientsClaim();

console.log('[Service Worker] ✅ skipWaiting() and clientsClaim() called');

// Precache all assets generated by Vite
const manifest = self.__WB_MANIFEST || [];
console.log('[Service Worker] 📦 Precaching', manifest.length, 'assets');
precacheAndRoute(manifest);

/*
 * Origem do Supabase, resolvida em build time a partir da mesma variável que o
 * app usa. Antes o domínio do projeto estava fixo em duas regex aqui — o que
 * significava que trocar de projeto (ou self-hospedar) desligava o cache
 * offline em silêncio, sem erro nenhum.
 *
 * Comparar origem + prefixo do caminho, em vez de regex sobre a URL inteira,
 * evita ter que escapar o host e funciona igual para supabase.co, domínio
 * próprio ou 127.0.0.1 em desenvolvimento.
 */
const SUPABASE_ORIGIN = (() => {
  try {
    return new URL(import.meta.env.VITE_SUPABASE_URL).origin;
  } catch {
    // Sem configuração válida não há o que cachear; as rotas abaixo nunca
    // casam e o SW segue funcionando para precache e push.
    console.warn('[Service Worker] VITE_SUPABASE_URL ausente ou inválida — cache do Supabase desativado');
    return null;
  }
})();

const isSupabasePath = (prefix) => ({ url }) =>
  SUPABASE_ORIGIN !== null && url.origin === SUPABASE_ORIGIN && url.pathname.startsWith(prefix);

// Cache Supabase API calls
registerRoute(
  isSupabasePath('/rest/'),
  new NetworkFirst({
    cacheName: 'supabase-api-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 60 * 5, // 5 minutes
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

// Cache Supabase Storage
registerRoute(
  isSupabasePath('/storage/'),
  new CacheFirst({
    cacheName: 'supabase-storage-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 60 * 60 * 24 * 7, // 7 days
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

// Cache images
registerRoute(
  /\.(?:png|jpg|jpeg|svg|gif|webp)$/,
  new CacheFirst({
    cacheName: 'images-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 60 * 60 * 24 * 30, // 30 days
      }),
    ],
  })
);

// Cache de navegação para SPA
const navigationRoute = new NavigationRoute(
  new NetworkFirst({
    cacheName: 'navigations',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 20,
        maxAgeSeconds: 60 * 60 * 24, // 1 dia
      }),
    ],
  })
);

registerRoute(navigationRoute);

// Listen for push events
self.addEventListener('push', (event) => {
  console.log('[Service Worker] Push received:', event);
  
  let notificationData = {
    title: 'Alerta Financeiro',
    body: 'Você tem uma nova notificação',
    icon: '/icon-192.png',
    badge: '/icon-192.png',
    data: {
      url: '/'
    }
  };

  if (event.data) {
    try {
      const parsed = event.data.json();
      notificationData = {
        title: parsed.title || notificationData.title,
        body: parsed.body || notificationData.body,
        icon: parsed.icon || notificationData.icon,
        badge: parsed.badge || notificationData.badge,
        data: {
          url: (parsed.data && parsed.data.url) || parsed.url || '/',
          ...(parsed.data || {}),
        },
        tag: parsed.tag || 'default',
        requireInteraction: parsed.requireInteraction || false,
      };
    } catch (err) {
      console.error('[Service Worker] Error parsing push data:', err);
    }
  }

  const promiseChain = self.registration.showNotification(
    notificationData.title,
    notificationData
  );

  event.waitUntil(promiseChain);
});

// Listen for notification clicks
self.addEventListener('notificationclick', (event) => {
  console.log('[Service Worker] Notification click received:', event);
  
  event.notification.close();

  const urlToOpen = new URL(
    event.notification.data?.url || '/', 
    self.location.origin
  ).href;

  const promiseChain = clients.matchAll({
    type: 'window',
    includeUncontrolled: true
  })
  .then((windowClients) => {
    // Check if there's already a window open with this URL
    for (let i = 0; i < windowClients.length; i++) {
      const client = windowClients[i];
      if (client.url === urlToOpen && 'focus' in client) {
        return client.focus();
      }
    }
    
    // Check if there's any window open that we can navigate
    if (windowClients.length > 0) {
      const client = windowClients[0];
      if ('navigate' in client && 'focus' in client) {
        client.navigate(urlToOpen);
        return client.focus();
      }
    }
    
    // If no window is open, open a new one
    if (clients.openWindow) {
      return clients.openWindow(urlToOpen);
    }
  });

  event.waitUntil(promiseChain);
});

// Installation event
self.addEventListener('install', (event) => {
  console.log('[Service Worker] 📥 Install event');
  event.waitUntil(self.skipWaiting());
});

// Activation event
self.addEventListener('activate', (event) => {
  console.log('[Service Worker] 🔄 Activate event');
  event.waitUntil(self.clients.claim());
});

console.log('[Service Worker] ✅ Custom SW with push notifications and Workbox loaded');
